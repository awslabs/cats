def generate_types(output_dir: Path | None = None) -> Path:
    """Generate cats_types.py with Protocol classes for typed fixtures.

    Defaults to config file's directory if output_dir not specified.

    The shared protocols describe the union of what the accounts under test resolve to after
    hierarchical settings: a handler enabled on any target, a role declared on any account, or
    ``allow_shell`` on any account puts its methods on the protocol. A method that is typed but
    not enabled for the account a test uses raises ``CatsConfigError`` at runtime, which is the
    documented behavior; a method that exists but is not typed would be the worse error.

    Raises ``CatsConfigError`` when the resolved config file does not exist: an absent file
    loads as an empty configuration, and the result would be a plausible-looking module with
    no account classes (a typo in ``CATS_CONFIG`` has the same outcome).
    """
    config_path = get_cats_config_filepath()
    require_config_file(config_path)
    settings = Settings()
    _reject_colliding_class_names(list(settings.accounts_under_test))
    accounts = settings.accounts_under_test.values()
    enabled_handlers = sorted(
        {
            handler.value
            for account in accounts
            for target in account.account_network_under_test.values()
            for handler in target.network_settings.enabled_network_handlers
        }
        | {handler.value for handler in settings.global_network_settings.enabled_network_handlers}
    )
    role_names = list(settings.global_account_settings.additional_roles)
    for account in accounts:
        role_names.extend(name for name in account.account_settings.additional_roles if name not in role_names)
    allow_shell = any(acc.account_settings.allow_shell for acc in accounts)
    output = TEMPLATE.render(
        config_path=config_path,
        role_names=role_names,
        accounts=settings.accounts_under_test,
        to_class_name=_to_class_name,
        enabled_handlers=enabled_handlers,
        allow_shell=allow_shell,
    )
    target_dir = output_dir or get_default_output_dir()
    output_path = target_dir / "cats_types.py"
    output_path.write_text(output.rstrip() + "\n", encoding="utf-8")
    return output_path


def _to_class_name(account_name: str) -> str:
    """Convert account_name to PascalCase class name.

    Preserves existing capitalization within each part, only ensures first char is uppercase.
    Examples: 'my-account' -> 'MyAccountAccount', 'SharedServices' -> 'SharedServicesAccount'.
    Not injective: `my_account`, `my__account` and `MyAccount` all give `MyAccountAccount`, which
    `_reject_colliding_class_names` turns into a config error rather than a file that defines
    one class three times.
    """
    parts = account_name.replace("-", "_").split("_")
    return "".join(part[0].upper() + part[1:] if part else "" for part in parts) + "Account"


def _reject_colliding_class_names(keynames: list[str]) -> None:
    """Every account gets its own protocol class; two keynames that PascalCase to one name would be a mypy no-redef and a silent last-wins."""
    keynames_by_class: dict[str, list[str]] = {}
    for keyname in keynames:
        keynames_by_class.setdefault(_to_class_name(keyname), []).append(keyname)
    for class_name, colliding in keynames_by_class.items():
        if len(colliding) > 1:
            raise CatsConfigError(
                f"account keynames {', '.join(repr(keyname) for keyname in colliding)} all map to the generated class '{class_name}' "
                + "(the keyname in PascalCase with '_' and '-' removed, plus 'Account'); rename one so each account gets its own class."
            )
